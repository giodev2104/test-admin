-- =====================================================================
--  Webcare · Servicios contratados por cada cliente
-- =====================================================================
-- Ejecútalo en Supabase > SQL Editor DESPUÉS de supabase_tarifas_2026.sql.
-- No borra datos y se puede ejecutar varias veces.
--
-- Cada cliente tiene una lista de servicios: su plan de web, su plan de mantenimiento o renting,
-- y sus extras y packs. El cliente los pide desde «Servicios» en su portal (se crea un caso en el
-- panel y el servicio queda «pendiente»); al pasar el caso a «Aceptado» el servicio queda «activo»
-- y, si es un plan, sustituye al anterior. Al denegarlo queda «rechazado».
-- =====================================================================

create table if not exists public.servicios_cliente (
  id            bigint generated by default as identity primary key,
  cliente_id    uuid not null references public.clientes(id) on delete cascade,
  tipo          text not null check (tipo in ('web', 'mantenimiento', 'renting', 'extra', 'pack')),
  nombre        text not null check (length(nombre) between 1 and 150),
  precio        text check (precio is null or length(precio) <= 60),
  estado        text not null default 'pendiente' check (estado in ('pendiente', 'activo', 'baja', 'rechazado')),
  caso_id       bigint references public.reportes(id) on delete set null,
  caso_baja_id  bigint references public.reportes(id) on delete set null,
  nota          text check (nota is null or length(nota) <= 500),
  creado_en     timestamptz not null default now(),
  activado_en   timestamptz,
  baja_en       timestamptz
);
create index if not exists servicios_cliente_cliente_idx on public.servicios_cliente (cliente_id);
create index if not exists servicios_cliente_caso_idx on public.servicios_cliente (caso_id);
alter table public.servicios_cliente enable row level security;
revoke all on public.servicios_cliente from anon, authenticated;
grant select, insert, update, delete on public.servicios_cliente to authenticated;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'servicios_cliente' and policyname = 'staff_servicios') then
    create policy "staff_servicios" on public.servicios_cliente for all to authenticated
      using (public.es_staff()) with check (public.es_staff());
  end if;
end
$$;

-- Qué tipo de servicio es un nombre del catálogo (null = no es un servicio)
create or replace function public.servicio_tipo(p_nombre text)
returns text language sql immutable as $$
  select case
    when p_nombre like 'Mantenimiento %' then 'mantenimiento'
    when p_nombre like 'Renting Plan %' then 'renting'
    when p_nombre like 'Plan %' then 'web'
    when p_nombre like 'Pack %' then 'pack'
    when p_nombre like 'EXT-%' then 'extra'
  end;
$$;

-- El cliente pide un servicio nuevo o un cambio de plan
create or replace function public.cliente_pedir_servicio(p_token text, p_tipo text, p_nombre text, p_precio text)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare cid uuid := _cliente_de_token(p_token); c clientes; r reportes; s servicios_cliente; actual text; nom text := left(trim(coalesce(p_nombre, '')), 150);
begin
  if cid is null then raise exception 'SESION_CADUCADA'; end if;
  if p_tipo is null or p_tipo not in ('web', 'mantenimiento', 'renting', 'extra', 'pack') then raise exception 'Tipo de servicio no válido.'; end if;
  if nom = '' then raise exception 'Elige un servicio.'; end if;
  if exists (select 1 from servicios_cliente where cliente_id = cid and nombre = nom and estado = 'pendiente') then
    raise exception 'Ya has pedido «%»; el equipo lo está revisando.', nom;
  end if;
  if p_tipo in ('web', 'mantenimiento', 'renting') and exists (select 1 from servicios_cliente where cliente_id = cid and nombre = nom and estado = 'activo') then
    raise exception 'Ya tienes «%».', nom;
  end if;
  select * into c from clientes where id = cid;
  select plan into actual from webs_cliente where cliente_id = cid;
  if p_tipo in ('mantenimiento', 'renting') then
    if nom not in ('Mantenimiento Esencial', 'Mantenimiento Pro', 'Renting Plan Lanzamiento', 'Renting Plan Negocio', 'Renting Plan Ecommerce') then
      raise exception 'Plan no válido.';
    end if;
    if exists (select 1 from reportes where cliente_id = cid and plan_solicitado is not null
               and eliminado_en is null and estado not in ('Aceptado', 'Denegado')) then
      raise exception 'Ya tienes una solicitud de cambio de plan pendiente.';
    end if;
    insert into reportes (tipo_reporte, titulo, descripcion, usuario_discord, email, dominio, plan, plan_solicitado, estado, cliente_id)
    values ('Cambio', 'Cambio de plan a ' || nom,
            'El cliente pide pasar de ' || coalesce(actual, 'sin plan') || ' a ' || nom || coalesce(' (' || p_precio || ')', '')
              || '. Al pasar este caso a «Aceptado», su plan cambiará solo en el portal.',
            c.nombre, c.email, c.dominio, actual, nom, 'Entrada de leads', cid)
    returning * into r;
  else
    insert into reportes (tipo_reporte, titulo, descripcion, usuario_discord, email, dominio, plan, estado, cliente_id)
    values ('Cambio', case when p_tipo = 'web' then 'Plan web: ' else 'Contratar: ' end || nom,
            'El cliente quiere contratar «' || nom || '»' || coalesce(' (' || p_precio || ')', '')
              || ' desde la sección Servicios de su portal. Al pasar este caso a «Aceptado», quedará activo en su lista de servicios.',
            c.nombre, c.email, c.dominio, actual, 'Entrada de leads', cid)
    returning * into r;
  end if;
  insert into servicios_cliente (cliente_id, tipo, nombre, precio, estado, caso_id)
    values (cid, p_tipo, nom, left(p_precio, 60), 'pendiente', r.id) returning * into s;
  return json_build_object('caso', json_build_object('id', r.id, 'tipo_reporte', r.tipo_reporte, 'titulo', r.titulo, 'estado', r.estado,
                             'plan', r.plan, 'plan_solicitado', r.plan_solicitado, 'dominio', r.dominio, 'urgencia', r.urgencia,
                             'created_at', r.created_at, 'origen', r.origen),
                           'servicio', to_json(s));
end
$$;
revoke all on function public.cliente_pedir_servicio(text, text, text, text) from public;
grant execute on function public.cliente_pedir_servicio(text, text, text, text) to anon, authenticated;

-- El cliente pide la baja de un extra o pack activo (los planes se dan de baja con «Darme de baja»)
create or replace function public.cliente_baja_servicio(p_token text, p_servicio bigint)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare cid uuid := _cliente_de_token(p_token); c clientes; r reportes; s servicios_cliente;
begin
  if cid is null then raise exception 'SESION_CADUCADA'; end if;
  select * into s from servicios_cliente where id = p_servicio and cliente_id = cid;
  if s.id is null or s.estado <> 'activo' then raise exception 'Ese servicio no está activo.'; end if;
  if s.tipo not in ('extra', 'pack') then raise exception 'Para dejar tu plan usa «Darme de baja».'; end if;
  if s.caso_baja_id is not null and exists (select 1 from reportes where id = s.caso_baja_id and estado not in ('Aceptado', 'Denegado') and eliminado_en is null) then
    raise exception 'Ya has pedido la baja de este servicio.';
  end if;
  select * into c from clientes where id = cid;
  insert into reportes (tipo_reporte, titulo, descripcion, usuario_discord, email, dominio, estado, cliente_id)
  values ('Cambio', 'Baja de servicio: ' || s.nombre,
          'El cliente pide dar de baja «' || s.nombre || '». Al pasar este caso a «Aceptado», dejará de aparecer como activo en su portal.',
          c.nombre, c.email, c.dominio, 'Entrada de leads', cid)
  returning * into r;
  update servicios_cliente set caso_baja_id = r.id where id = s.id;
  return json_build_object('id', r.id, 'tipo_reporte', r.tipo_reporte, 'titulo', r.titulo, 'estado', r.estado,
                           'plan', r.plan, 'dominio', r.dominio, 'urgencia', r.urgencia, 'created_at', r.created_at, 'origen', r.origen);
end
$$;
revoke all on function public.cliente_baja_servicio(text, bigint) from public;
grant execute on function public.cliente_baja_servicio(text, bigint) to anon, authenticated;

-- Al registrarse con un plan, extra o pack, ese servicio queda pendiente en su lista
create or replace function public.servicio_desde_alta()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.tipo_reporte = 'Lead' and new.cliente_id is not null and public.servicio_tipo(new.plan) is not null then
    insert into servicios_cliente (cliente_id, tipo, nombre, estado, caso_id)
      values (new.cliente_id, public.servicio_tipo(new.plan), left(new.plan, 150), 'pendiente', new.id);
  end if;
  return new;
end
$$;
create or replace trigger reportes_servicio_alta after insert on public.reportes
  for each row execute function public.servicio_desde_alta();

-- Al aceptar o denegar el caso, el servicio se activa, se rechaza o se da de baja
create or replace function public.servicio_segun_caso()
returns trigger language plpgsql security definer set search_path = public as $$
declare s servicios_cliente;
begin
  if new.estado = old.estado then return new; end if;
  if new.estado = 'Aceptado' then
    for s in update servicios_cliente set estado = 'activo', activado_en = now()
             where caso_id = new.id and estado = 'pendiente' returning * loop
      if s.tipo = 'web' then
        update servicios_cliente set estado = 'baja', baja_en = now()
          where cliente_id = s.cliente_id and tipo = 'web' and estado = 'activo' and id <> s.id;
      elsif s.tipo in ('mantenimiento', 'renting') then
        update servicios_cliente set estado = 'baja', baja_en = now()
          where cliente_id = s.cliente_id and tipo in ('mantenimiento', 'renting') and estado = 'activo' and id <> s.id;
      end if;
    end loop;
    update servicios_cliente set estado = 'baja', baja_en = now() where caso_baja_id = new.id and estado = 'activo';
    if new.plan_solicitado = 'Cancelar' and new.cliente_id is not null then
      update servicios_cliente set estado = 'baja', baja_en = now()
        where cliente_id = new.cliente_id and tipo in ('mantenimiento', 'renting') and estado = 'activo';
    end if;
  elsif new.estado = 'Denegado' then
    update servicios_cliente set estado = 'rechazado' where caso_id = new.id and estado = 'pendiente';
    update servicios_cliente set caso_baja_id = null where caso_baja_id = new.id;
  end if;
  return new;
end
$$;
create or replace trigger reportes_servicio_estado after update of estado on public.reportes
  for each row execute function public.servicio_segun_caso();

