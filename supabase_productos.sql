-- =====================================================================
--  Velority · Catálogo de productos gestionado por el cliente
-- =====================================================================
-- Ejecútalo en Supabase > SQL Editor DESPUÉS de supabase_invitados_permisos.sql.
-- No borra datos y se puede ejecutar varias veces.
--
-- El equipo activa el catálogo de un cliente desde el panel (ficha completa > Catálogo de productos).
-- El cliente sube sus productos desde la pestaña «Catálogo» del portal (función «productos») y su web
-- los muestra con el script https://velority.es/catalogo.js, que los pide a la función con la «clave»
-- pública del catálogo. Así funciona igual en velority.cloud que en el dominio propio del cliente.
-- Las fotos van al bucket PÚBLICO «productos» (las enseña la web), en la carpeta de la clave.
-- =====================================================================

create table if not exists public.catalogos (
  cliente_id     uuid primary key references public.clientes(id) on delete cascade,
  activo         boolean not null default false,
  limite         int not null default 30 check (limite between 1 and 1000),
  -- Pública: identifica el catálogo en la web del cliente (no da acceso a nada más)
  clave          text not null unique default substr(md5(gen_random_uuid()::text), 1, 16),
  activado_por   text,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.productos (
  id             bigint generated by default as identity primary key,
  cliente_id     uuid not null references public.clientes(id) on delete cascade,
  nombre         text not null check (length(nombre) between 1 and 120),
  descripcion    text check (descripcion is null or length(descripcion) <= 2000),
  precio         numeric(10,2) check (precio is null or precio >= 0),
  categoria      text check (categoria is null or length(categoria) <= 60),
  fotos          text[] not null default '{}' check (cardinality(fotos) <= 5),
  visible        boolean not null default true,
  destacado      boolean not null default false,
  orden          int not null default 0,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists productos_cliente_idx on public.productos (cliente_id, orden);

alter table public.catalogos enable row level security;
alter table public.productos enable row level security;
revoke all on public.catalogos, public.productos from anon, authenticated;
grant select, insert, update, delete on public.catalogos, public.productos to authenticated;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'catalogos' and policyname = 'staff_catalogos') then
    create policy "staff_catalogos" on public.catalogos for all to authenticated using (public.es_staff()) with check (public.es_staff());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'productos' and policyname = 'staff_productos') then
    create policy "staff_productos" on public.productos for all to authenticated using (public.es_staff()) with check (public.es_staff());
  end if;
end
$$;

-- Fotos: bucket público (solo lectura por URL); suben el cliente (URL firmada de la función) y el equipo
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('productos', 'productos', true, 3145728, array['image/jpeg', 'image/webp', 'image/png'])
on conflict (id) do update set public = true, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'staff_sube_productos') then
    create policy "staff_sube_productos" on storage.objects for insert to authenticated
      with check (bucket_id = 'productos' and public.es_staff());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'staff_quita_productos') then
    create policy "staff_quita_productos" on storage.objects for delete to authenticated
      using (bucket_id = 'productos' and public.es_staff());
  end if;
end
$$;

-- Nuevo permiso para personas invitadas: «catalogo»
alter table public.boveda_invitados drop constraint if exists boveda_invitados_permisos_check;
alter table public.boveda_invitados add constraint boveda_invitados_permisos_check
  check (permisos <@ array['chat','web','servicios','facturacion','accesos','catalogo'] and cardinality(permisos) > 0);

create or replace function public._permisos_validos(p text[])
returns text[] language plpgsql immutable set search_path = public as $$
declare r text[] := array(select distinct x from unnest(coalesce(p, '{}')) x where x = any(array['chat','web','servicios','facturacion','accesos','catalogo']));
begin
  if cardinality(r) = 0 then raise exception 'Marca al menos una sección a la que pueda entrar.'; end if;
  return r;
end $$;
revoke all on function public._permisos_validos(text[]) from public, anon, authenticated;

-- cliente_datos: añade «catalogo» (solo si está activo) y se lo quita a la persona invitada sin ese permiso
do $$
declare d text := pg_get_functiondef('public.cliente_datos(text)'::regprocedure);
begin
  if position('''catalogo''' in d) = 0 then
    d := replace(d, '''referidos'', json_build_object(''invitados''',
      '''catalogo'', (select json_build_object(''limite'', k.limite, ''clave'', k.clave) from catalogos k where k.cliente_id = cid and k.activo),
    ''referidos'', json_build_object(''invitados''');
    d := replace(d, '  p := inv.permisos;
', '  p := inv.permisos;
  if not (''catalogo'' = any(p)) then j := j - ''catalogo''; end if;
');
    execute d;
  end if;
end
$$;

-- Para la función «productos»: cliente de la sesión (titular o invitado con permiso «catalogo»).
-- La vista «Ver como cliente» del equipo también entra, pero marcada como solo lectura.
create or replace function public.servidor_catalogo_de_token(p_token text)
returns json language sql stable security definer set search_path = public, extensions as $$
  select case when a is not null then json_build_object('cliente_id', a, 'solo_lectura', false)
              when l is not null then json_build_object('cliente_id', l, 'solo_lectura', true) end
  from (select public._acceso(p_token, 'catalogo') a, public._cliente_de_token_lectura(p_token) l) x;
$$;
revoke all on function public.servidor_catalogo_de_token(text) from public, anon, authenticated;
grant execute on function public.servidor_catalogo_de_token(text) to service_role;

