-- Avisos push al móvil del equipo: cuando un cliente crea un caso o escribe en uno.
-- Requiere: supabase_mejoras.sql (tabla «ajustes» con url_proyecto y secreto_cron) y la función «push» desplegada.

-- Móviles del equipo que reciben avisos. Solo la gestiona el servidor (función «push»): ni anon ni authenticated la ven.
create table if not exists public.push_suscripciones (
  id bigint generated by default as identity primary key,
  usuario text not null references public.staff(usuario) on delete cascade on update cascade,
  endpoint text not null unique check (endpoint ~ '^https://'),
  p256dh text not null,
  auth text not null,
  dispositivo text,
  creado_en timestamptz not null default now(),
  ultimo_envio_en timestamptz
);
alter table public.push_suscripciones enable row level security;
revoke all on public.push_suscripciones from anon, authenticated;

-- Último aviso push de cada caso (para no mandar uno por cada mensaje seguido)
alter table public.reportes add column if not exists aviso_push_en timestamptz;

-- Disparador: llama a la función «push». Nunca bloquea el alta del caso o del mensaje si algo falla.
create or replace function public._avisar_push()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare u text; s text; cuerpo jsonb;
begin
  -- Lo que crea o escribe el propio equipo desde el panel no se avisa
  if public.es_staff() then return new; end if;
  if tg_table_name = 'reportes' then
    if new.eliminado_en is not null then return new; end if;
    cuerpo := jsonb_build_object('accion', 'caso', 'id', new.id);
  else
    if new.autor_tipo <> 'usuario' then return new; end if;
    -- El primer mensaje de un caso recién creado ya va en el aviso de «Nuevo caso»
    if exists (select 1 from reportes where id = new.caso_id and created_at > now() - interval '1 minute') then return new; end if;
    cuerpo := jsonb_build_object('accion', 'mensaje', 'id', new.caso_id, 'texto', left(coalesce(new.texto, ''), 300));
  end if;
  select valor into u from ajustes where clave = 'url_proyecto';
  select valor into s from ajustes where clave = 'secreto_cron';
  if u is null or s is null then return new; end if;
  perform net.http_post(
    url := u || '/functions/v1/push',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-secreto', s),
    body := cuerpo,
    timeout_milliseconds := 15000);
  return new;
exception when others then
  return new;
end
$$;
revoke all on function public._avisar_push() from public, anon, authenticated;

drop trigger if exists avisar_push_caso on public.reportes;
create trigger avisar_push_caso after insert on public.reportes
  for each row execute function public._avisar_push();
drop trigger if exists avisar_push_mensaje on public.mensajes_caso;
create trigger avisar_push_mensaje after insert on public.mensajes_caso
  for each row execute function public._avisar_push();
