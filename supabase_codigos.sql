-- =====================================================================
--  Velority · Códigos promocionales (se crean en el panel y el cliente los usa al pagar con Stripe)
-- =====================================================================
-- El cliente escribe el código en «Antes de pagar»; la función «pago» lo valida aquí y descuenta el importe en Stripe.
-- En las webs por fases (50 % + 50 %) el código se usa una vez y se aplica a las dos partes.
-- Solo los propietarios del panel crean, cambian o borran códigos. Ejecútalo en Supabase > SQL Editor (se puede repetir).

create table if not exists public.codigos_promo (
  id                 bigint generated by default as identity primary key,
  codigo             text not null unique check (codigo ~ '^[A-Z0-9_-]{3,30}$'),
  tipo               text not null default 'porcentaje' check (tipo in ('porcentaje', 'importe')),
  valor              numeric(10,2) not null check (valor > 0),
  aplica             text not null default 'todo' check (aplica in ('todo', 'web', 'extra', 'pack')),
  activo             boolean not null default true,
  hasta              date,                                   -- último día de validez (hora de España); vacío = sin caducidad
  usos_max           int check (usos_max is null or usos_max > 0),
  usos               int not null default 0,
  uno_por_cliente    boolean not null default true,
  nota               text check (nota is null or length(nota) <= 300),
  creado_por         text,
  creado_en          timestamptz not null default now(),
  check (tipo <> 'porcentaje' or valor <= 100)
);
create table if not exists public.codigos_usos (
  id          bigint generated by default as identity primary key,
  codigo_id   bigint not null references public.codigos_promo(id) on delete cascade,
  cliente_id  uuid references public.clientes(id) on delete set null,
  sesion      text not null unique,                          -- sesión de Stripe: un pago cuenta una sola vez
  descuento   numeric(10,2),
  creado_en   timestamptz not null default now()
);
create index if not exists codigos_usos_codigo_idx on public.codigos_usos (codigo_id, cliente_id);
alter table public.servicios_cliente add column if not exists codigo_id bigint references public.codigos_promo(id) on delete set null;

alter table public.codigos_promo enable row level security;
alter table public.codigos_usos enable row level security;
revoke all on public.codigos_promo, public.codigos_usos from anon, authenticated;
grant select, insert, update, delete on public.codigos_promo to authenticated;
grant select on public.codigos_usos to authenticated;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'codigos_promo' and policyname = 'staff_lee_codigos') then
    create policy "staff_lee_codigos" on public.codigos_promo for select to authenticated using (public.es_staff());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'codigos_promo' and policyname = 'duenos_gestionan_codigos') then
    create policy "duenos_gestionan_codigos" on public.codigos_promo for all to authenticated
      using (exists (select 1 from public.staff s where s.usuario = public.staff_usuario() and s.es_dueno))
      with check (exists (select 1 from public.staff s where s.usuario = public.staff_usuario() and s.es_dueno));
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'codigos_usos' and policyname = 'staff_lee_usos_codigos') then
    create policy "staff_lee_usos_codigos" on public.codigos_usos for select to authenticated using (public.es_staff());
  end if;
end
$$;

-- ¿Sirve este código para este cliente y este tipo de servicio? Devuelve {id, codigo, tipo, valor} o un error legible.
create or replace function public.servidor_validar_codigo(p_codigo text, p_cliente uuid, p_tipo text)
returns json language plpgsql stable security definer set search_path = public as $$
declare c codigos_promo; hoy date := (now() at time zone 'Europe/Madrid')::date;
begin
  select * into c from codigos_promo where codigo = upper(trim(p_codigo));
  if c.id is null or not c.activo then raise exception 'El código no existe o ya no está activo.'; end if;
  if c.hasta is not null and hoy > c.hasta then raise exception 'Este código caducó el %.', to_char(c.hasta, 'DD/MM/YYYY'); end if;
  if c.usos_max is not null and c.usos >= c.usos_max then raise exception 'Este código ya se ha agotado.'; end if;
  if c.aplica <> 'todo' and c.aplica <> p_tipo then
    raise exception 'Este código solo sirve para %.', case c.aplica when 'web' then 'la creación de webs' when 'extra' then 'servicios adicionales' else 'packs' end;
  end if;
  if c.uno_por_cliente and exists (select 1 from codigos_usos u where u.codigo_id = c.id and u.cliente_id = p_cliente) then
    raise exception 'Ya has usado este código.';
  end if;
  return json_build_object('id', c.id, 'codigo', c.codigo, 'tipo', c.tipo, 'valor', c.valor);
end $$;

-- Apunta el uso tras un pago confirmado (una sola vez por sesión de Stripe) y, en webs por fases, lo deja fijado en el pedido
create or replace function public.servidor_usar_codigo(p_codigo bigint, p_cliente uuid, p_sesion text, p_descuento numeric, p_servicio bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  insert into codigos_usos (codigo_id, cliente_id, sesion, descuento) values (p_codigo, p_cliente, p_sesion, p_descuento)
  on conflict (sesion) do nothing;
  if found then update codigos_promo set usos = usos + 1 where id = p_codigo; end if;
  if p_servicio is not null then update servicios_cliente set codigo_id = p_codigo where id = p_servicio and codigo_id is null; end if;
end $$;
revoke all on function public.servidor_validar_codigo(text, uuid, text), public.servidor_usar_codigo(bigint, uuid, text, numeric, bigint) from public, anon, authenticated;
grant execute on function public.servidor_validar_codigo(text, uuid, text), public.servidor_usar_codigo(bigint, uuid, text, numeric, bigint) to service_role;
