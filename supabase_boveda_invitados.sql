-- =====================================================================
--  Velority · Personas invitadas a la bóveda de accesos de un cliente
-- =====================================================================
-- El cliente crea en «Mi cuenta» usuarios (nombre, correo y contraseña) para otras personas: su socio, su empleado, su
-- gestor… Esas personas entran por el mismo formulario del portal, pero su sesión es distinta de la del cliente
-- (tabla sesiones_invitado): solo sirve para la bóveda (función «boveda») y no da acceso a pedidos, pagos ni chat.
-- Ejecútalo en Supabase > SQL Editor (se puede repetir). Usa pgcrypto (crypt, gen_salt, digest) del esquema extensions.

create table if not exists public.boveda_invitados (
  id             bigint generated by default as identity primary key,
  cliente_id     uuid not null references public.clientes(id) on delete cascade,
  nombre         text not null check (length(nombre) between 1 and 80),
  email          text not null unique check (email ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' and length(email) <= 320),
  clave_hash     text not null,
  creado_en      timestamptz not null default now(),
  ultimo_acceso  timestamptz
);
create index if not exists boveda_invitados_cliente_idx on public.boveda_invitados (cliente_id);
create table if not exists public.sesiones_invitado (
  token_hash   text primary key,
  invitado_id  bigint not null references public.boveda_invitados(id) on delete cascade,
  expira_en    timestamptz not null default now() + interval '12 hours'
);
alter table public.boveda_invitados enable row level security;
alter table public.sesiones_invitado enable row level security;
revoke all on public.boveda_invitados, public.sesiones_invitado from anon, authenticated;

-- Lista de invitados (solo el propio cliente, con su sesión)
create or replace function public.cliente_invitados(p_token text)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare cid uuid := _cliente_de_token(p_token);
begin
  if cid is null then raise exception 'Tu sesión ha caducado. Vuelve a entrar.'; end if;
  return coalesce((select json_agg(json_build_object('id', id, 'nombre', nombre, 'email', email, 'creado_en', creado_en, 'ultimo_acceso', ultimo_acceso) order by creado_en)
                   from boveda_invitados where cliente_id = cid), '[]'::json);
end $$;

create or replace function public.cliente_crear_invitado(p_token text, p_nombre text, p_email text, p_clave text)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare cid uuid := _cliente_de_token(p_token); e text := lower(trim(coalesce(p_email, ''))); n text := trim(coalesce(p_nombre, ''));
begin
  if cid is null then raise exception 'Tu sesión ha caducado. Vuelve a entrar.'; end if;
  if n = '' or length(n) > 80 then raise exception 'Escribe el nombre de la persona.'; end if;
  if e !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then raise exception 'Escribe un correo válido.'; end if;
  if length(coalesce(p_clave, '')) < 10 then raise exception 'La contraseña debe tener al menos 10 caracteres.'; end if;
  if exists (select 1 from clientes where email = e) or exists (select 1 from boveda_invitados where email = e) then
    raise exception 'Ese correo ya tiene una cuenta. Usa otro.';
  end if;
  if (select count(*) from boveda_invitados where cliente_id = cid) >= 10 then raise exception 'Puedes invitar como máximo a 10 personas.'; end if;
  insert into boveda_invitados (cliente_id, nombre, email, clave_hash) values (cid, n, e, crypt(p_clave, gen_salt('bf')));
  return cliente_invitados(p_token);
end $$;

create or replace function public.cliente_borrar_invitado(p_token text, p_id bigint)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare cid uuid := _cliente_de_token(p_token);
begin
  if cid is null then raise exception 'Tu sesión ha caducado. Vuelve a entrar.'; end if;
  delete from boveda_invitados where id = p_id and cliente_id = cid;   -- sus sesiones se borran en cascada
  return cliente_invitados(p_token);
end $$;

-- Entrar como invitado (mismo límite de intentos que el acceso de clientes)
create or replace function public.invitado_entrar(p_email text, p_clave text)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare e text := lower(trim(coalesce(p_email, ''))); ip text := _ip(); i boveda_invitados; t text := encode(gen_random_bytes(32), 'hex'); negocio text;
begin
  if _excedido('invitado-correo:' || e, 8, interval '15 minutes') or _excedido('invitado-ip:' || ip, 30, interval '15 minutes') then
    return json_build_object('error', 'Demasiados intentos. Espera 15 minutos y vuelve a probar.');
  end if;
  perform _anotar('invitado-correo:' || e);
  perform _anotar('invitado-ip:' || ip);
  select * into i from boveda_invitados where email = e;
  if i.id is null or i.clave_hash <> crypt(coalesce(p_clave, ''), i.clave_hash) then
    perform pg_sleep(0.5);
    return json_build_object('error', 'Correo o contraseña incorrectos.');
  end if;
  delete from intentos where clave = 'invitado-correo:' || e;
  delete from sesiones_invitado where expira_en < now();
  insert into sesiones_invitado (token_hash, invitado_id) values (encode(digest(t, 'sha256'), 'hex'), i.id);
  update boveda_invitados set ultimo_acceso = now() where id = i.id;
  select coalesce(nullif(trim(c.nombre), ''), c.email) into negocio from clientes c where c.id = i.cliente_id;
  return json_build_object('token', t, 'nombre', i.nombre, 'negocio', negocio);
end $$;

create or replace function public.invitado_salir(p_token text)
returns void language sql security definer set search_path = public, extensions as $$
  delete from sesiones_invitado where token_hash = encode(digest(coalesce(p_token, ''), 'sha256'), 'hex');
$$;

-- Para la función «boveda» (service_role): de quién es la sesión del invitado
create or replace function public.servidor_invitado_de_token(p_token text)
returns json language sql stable security definer set search_path = public, extensions as $$
  select json_build_object('cliente_id', i.cliente_id, 'nombre', i.nombre)
    from sesiones_invitado s join boveda_invitados i on i.id = s.invitado_id
   where s.token_hash = encode(digest(coalesce(p_token, ''), 'sha256'), 'hex') and s.expira_en > now();
$$;

revoke all on function public.cliente_invitados(text), public.cliente_crear_invitado(text, text, text, text), public.cliente_borrar_invitado(text, bigint),
  public.invitado_entrar(text, text), public.invitado_salir(text), public.servidor_invitado_de_token(text) from public;
grant execute on function public.cliente_invitados(text), public.cliente_crear_invitado(text, text, text, text), public.cliente_borrar_invitado(text, bigint),
  public.invitado_entrar(text, text), public.invitado_salir(text) to anon, authenticated;
grant execute on function public.servidor_invitado_de_token(text) to service_role;
