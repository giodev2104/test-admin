-- =====================================================================
--  Velority · Clientes potenciales (negocios de Google Maps sin página web)
-- =====================================================================
-- La función «prospectos» busca negocios en Google Maps (Places API) y guarda aquí los que no tienen web propia.
-- Desde el panel (Correo > Clientes potenciales) se les escribe una propuesta y se marca a quién ya se le envió.
-- Ejecútalo en Supabase > SQL Editor. Se puede ejecutar varias veces.

create table if not exists public.prospectos (
  id            bigint generated by default as identity primary key,
  place_id      text not null unique,                       -- identificador del negocio en Google Maps
  nombre        text not null check (length(nombre) <= 300),
  categoria     text,
  direccion     text,
  ciudad        text,
  telefono      text,
  maps_url      text,
  valoracion    numeric(2,1),
  n_resenas     int,
  web_social    text,                                       -- si en Google solo tiene Facebook/Instagram
  email         text check (email is null or length(email) <= 320),
  estado        text not null default 'nuevo' check (estado in ('nuevo', 'contactado', 'respondido', 'descartado', 'cliente')),
  notas         text check (notas is null or length(notas) <= 2000),
  busqueda      text,                                       -- con qué búsqueda apareció
  contactado_en timestamptz,
  contactado_por text,
  creado_en     timestamptz not null default now()
);
create index if not exists prospectos_estado_idx on public.prospectos (estado, creado_en desc);

alter table public.prospectos enable row level security;
revoke all on public.prospectos from anon, authenticated;
grant select, update, delete on public.prospectos to authenticated;   -- los crea la función (service_role)
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'prospectos' and policyname = 'staff_prospectos') then
    create policy "staff_prospectos" on public.prospectos for all to authenticated using (public.es_staff()) with check (public.es_staff());
  end if;
end
$$;

-- Límite de Google Maps: cuenta las peticiones de cada mes (el mes de facturación de Google, hora del Pacífico)
-- y se niega a pasar del máximo, para no salir nunca del plan gratuito. Lo usa la función «prospectos».
create or replace function public.servidor_gastar_google(p_max int)
returns int language plpgsql security definer set search_path = public as $$
declare mes text := to_char(now() at time zone 'America/Los_Angeles', 'YYYY-MM'); usados int;
begin
  insert into ajustes_web (clave, valor, actualizado_por) values ('google_places_uso', jsonb_build_object('mes', mes, 'peticiones', 0), 'sistema')
  on conflict (clave) do nothing;
  select case when valor->>'mes' = mes then coalesce((valor->>'peticiones')::int, 0) else 0 end into usados
    from ajustes_web where clave = 'google_places_uso' for update;
  if usados >= p_max then return -1; end if;
  update ajustes_web set valor = jsonb_build_object('mes', mes, 'peticiones', usados + 1), actualizado_en = now() where clave = 'google_places_uso';
  return usados + 1;
end $$;
revoke all on function public.servidor_gastar_google(int) from public, anon, authenticated;
grant execute on function public.servidor_gastar_google(int) to service_role;
