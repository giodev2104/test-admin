-- 1) Tablas -------------------------------------------------------------
create table if not exists public.staff (
  usuario    text primary key check (usuario ~ '^[a-z0-9_.-]{3,30}$'),
  email      text not null unique,
  creado_por text default 'sistema',
  creado_en  timestamptz not null default now(),
  es_dueno   boolean not null default false
);

create table if not exists public.reportes (
  id                  bigint generated by default as identity primary key,
  created_at          timestamptz not null default now(),
  tipo_reporte        text not null default 'Cambio',
  titulo              text,
  descripcion         text,
  usuario_discord     text,            -- nombre del cliente
  email               text,
  telefono            text,
  dominio             text,
  plan                text,
  pruebas             text,
  estado              text not null default 'Entrada de leads',
  resuelto_en         timestamptz,
  responsable_usuario text references public.staff(usuario) on update cascade on delete set null,
  urgencia            double precision check (urgencia is null or urgencia between 0 and 1),
  eliminado_en        timestamptz,
  eliminado_por       text,
  cliente_id          uuid references auth.users(id) on delete set null
);
alter table public.reportes add column if not exists cliente_id uuid references auth.users(id) on delete set null;
create index if not exists reportes_cliente_id_idx on public.reportes (cliente_id);

create table if not exists public.notas_caso (
  id        bigint generated by default as identity primary key,
  caso_id   bigint not null references public.reportes(id) on delete cascade,
  autor     text not null,
  texto     text not null check (length(texto) between 1 and 1000),
  creado_en timestamptz not null default now()
);

create table if not exists public.mensajes_caso (
  id         bigint generated by default as identity primary key,
  caso_id    bigint not null references public.reportes(id) on delete cascade,
  autor_tipo text not null check (autor_tipo in ('staff', 'usuario')),
  autor      text,
  texto      text not null check (length(texto) between 1 and 2000),
  creado_en  timestamptz not null default now()
);

create table if not exists public.actividad_caso (
  id        bigint generated by default as identity primary key,
  caso_id   bigint not null references public.reportes(id) on delete cascade,
  tipo      text not null,     -- creado | estado | responsable | eliminado | restaurado
  anterior  text,
  nuevo     text,
  autor     text,
  creado_en timestamptz not null default now()
);

create index if not exists notas_caso_caso_idx     on public.notas_caso (caso_id);
create index if not exists mensajes_caso_caso_idx  on public.mensajes_caso (caso_id);
create index if not exists actividad_caso_caso_idx on public.actividad_caso (caso_id);

-- 2) Funciones de ayuda (security definer: evitan recursión en RLS) ------
create or replace function public.staff_usuario()
returns text language sql stable security definer set search_path = public as $$
  select usuario from public.staff where lower(email) = lower(auth.jwt() ->> 'email') limit 1;
$$;

create or replace function public.es_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select public.staff_usuario() is not null;
$$;

create or replace function public.caso_es_mio(caso bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.reportes
                 where id = caso and cliente_id = auth.uid() and eliminado_en is null);
$$;

revoke all on function public.staff_usuario(), public.es_staff(), public.caso_es_mio(bigint) from public;
grant execute on function public.staff_usuario(), public.es_staff(), public.caso_es_mio(bigint) to authenticated;

-- 3) Seguridad (RLS) -----------------------------------------------------
alter table public.staff          enable row level security;
alter table public.reportes       enable row level security;
alter table public.notas_caso     enable row level security;
alter table public.mensajes_caso  enable row level security;
alter table public.actividad_caso enable row level security;

revoke all on public.staff, public.reportes, public.notas_caso, public.mensajes_caso, public.actividad_caso from anon;
grant select on public.staff to authenticated;          -- altas/bajas solo con la función gestionar-staff
grant select, insert, update on public.reportes to authenticated;
grant select, insert, delete on public.notas_caso to authenticated;
grant select, insert on public.mensajes_caso to authenticated;
grant select on public.actividad_caso to authenticated;  -- la escribe el trigger

-- staff
drop policy if exists "staff_lee_staff" on public.staff;
create policy "staff_lee_staff" on public.staff for select to authenticated using (public.es_staff());

-- reportes: el staff ve y edita todo; el cliente solo ve y crea los suyos
drop policy if exists "staff_lee_casos" on public.reportes;
create policy "staff_lee_casos" on public.reportes for select to authenticated using (public.es_staff());
drop policy if exists "staff_edita_casos" on public.reportes;
create policy "staff_edita_casos" on public.reportes for update to authenticated
  using (public.es_staff()) with check (public.es_staff());

drop policy if exists "cliente_ve_sus_casos" on public.reportes;
create policy "cliente_ve_sus_casos" on public.reportes for select to authenticated
  using (cliente_id = auth.uid() and eliminado_en is null);
drop policy if exists "cliente_crea_sus_casos" on public.reportes;
create policy "cliente_crea_sus_casos" on public.reportes for insert to authenticated
  with check (cliente_id = auth.uid() and estado = 'Entrada de leads'
              and tipo_reporte in ('Lead', 'Cambio', 'Incidencia', 'Duda')
              and responsable_usuario is null and eliminado_en is null);

-- notas internas: solo el staff (cada uno borra las suyas)
drop policy if exists "staff_lee_notas" on public.notas_caso;
create policy "staff_lee_notas" on public.notas_caso for select to authenticated using (public.es_staff());
drop policy if exists "staff_crea_notas" on public.notas_caso;
create policy "staff_crea_notas" on public.notas_caso for insert to authenticated
  with check (autor = public.staff_usuario());
drop policy if exists "staff_borra_sus_notas" on public.notas_caso;
create policy "staff_borra_sus_notas" on public.notas_caso for delete to authenticated
  using (autor = public.staff_usuario());

-- chat con el cliente
drop policy if exists "staff_lee_chat" on public.mensajes_caso;
create policy "staff_lee_chat" on public.mensajes_caso for select to authenticated using (public.es_staff());
drop policy if exists "staff_escribe_chat" on public.mensajes_caso;
create policy "staff_escribe_chat" on public.mensajes_caso for insert to authenticated
  with check (autor_tipo = 'staff' and autor = public.staff_usuario());
drop policy if exists "cliente_lee_su_chat" on public.mensajes_caso;
create policy "cliente_lee_su_chat" on public.mensajes_caso for select to authenticated
  using (public.caso_es_mio(caso_id));
drop policy if exists "cliente_escribe_su_chat" on public.mensajes_caso;
create policy "cliente_escribe_su_chat" on public.mensajes_caso for insert to authenticated
  with check (autor_tipo = 'usuario' and autor is null and public.caso_es_mio(caso_id));

-- historial: solo el staff
drop policy if exists "staff_lee_actividad" on public.actividad_caso;
create policy "staff_lee_actividad" on public.actividad_caso for select to authenticated using (public.es_staff());

-- 4) Historial automático de cada caso -----------------------------------
create or replace function public.registrar_actividad()
returns trigger language plpgsql security definer set search_path = public as $$
declare quien text := coalesce(public.staff_usuario(), case when auth.uid() is null then 'formulario' else 'sistema' end);
begin
  if tg_op = 'INSERT' then
    insert into actividad_caso (caso_id, tipo, nuevo, autor) values (new.id, 'creado', new.estado, quien);
    return new;
  end if;
  if new.estado is distinct from old.estado then
    insert into actividad_caso (caso_id, tipo, anterior, nuevo, autor) values (new.id, 'estado', old.estado, new.estado, quien);
  end if;
  if new.responsable_usuario is distinct from old.responsable_usuario then
    insert into actividad_caso (caso_id, tipo, anterior, nuevo, autor) values (new.id, 'responsable', old.responsable_usuario, new.responsable_usuario, quien);
  end if;
  if new.eliminado_en is distinct from old.eliminado_en then
    insert into actividad_caso (caso_id, tipo, autor) values (new.id, case when new.eliminado_en is null then 'restaurado' else 'eliminado' end, quien);
  end if;
  return new;
end $$;

drop trigger if exists reportes_actividad on public.reportes;
create trigger reportes_actividad after insert or update on public.reportes
  for each row execute function public.registrar_actividad();

-- 5) Tiempo real -----------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['reportes', 'notas_caso', 'mensajes_caso', 'actividad_caso'] loop
    if not exists (select 1 from pg_publication_tables
                   where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;

-- 6) Comprobación: todas deben salir con rowsecurity = true -------------
select tablename, rowsecurity from pg_tables
where schemaname = 'public' and tablename in ('staff', 'reportes', 'notas_caso', 'mensajes_caso', 'actividad_caso');

