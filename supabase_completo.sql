create extension if not exists pgcrypto with schema extensions;

-- 1) Tablas -------------------------------------------------------------
create table public.staff (
  usuario    text primary key check (usuario ~ '^[a-z0-9_.-]{3,30}$'),
  email      text not null unique check (email = lower(email)),
  creado_por text not null default 'sistema',
  creado_en  timestamptz not null default now(),
  es_dueno   boolean not null default false
);

create table public.clientes (
  id         uuid primary key default gen_random_uuid(),
  email      text not null unique check (email = lower(email)),
  nombre     text not null,
  dominio    text,
  clave_hash text not null,                -- contraseña cifrada con bcrypt
  creado_en  timestamptz not null default now()
);

create table public.sesiones_cliente (
  token_hash text primary key,              -- se guarda el hash, nunca el token
  cliente_id uuid not null references public.clientes(id) on delete cascade,
  creado_en  timestamptz not null default now(),
  expira_en  timestamptz not null default now() + interval '30 days'
);

create table public.reportes (
  id                  bigint generated by default as identity primary key,
  created_at          timestamptz not null default now(),
  tipo_reporte        text not null default 'Cambio'
                      check (tipo_reporte in ('Lead', 'Cambio', 'Incidencia', 'Duda')),
  titulo              text,
  descripcion         text,
  usuario_discord     text,                 -- nombre del cliente
  email               text,
  telefono            text,
  dominio             text,
  plan                text,
  pruebas             text,
  estado              text not null default 'Entrada de leads'
                      check (estado in ('Entrada de leads', 'Formulario enviado', 'Formulario recibido', 'Interesado',
                                        'Propuesta enviada', 'Seguimiento', 'Aceptado', 'Denegado')),
  resuelto_en         timestamptz,
  responsable_usuario text references public.staff(usuario) on update cascade on delete set null,
  urgencia            double precision check (urgencia is null or urgencia between 0 and 1),
  eliminado_en        timestamptz,
  eliminado_por       text,
  cliente_id          uuid references public.clientes(id) on delete set null
);

create table public.notas_caso (
  id        bigint generated by default as identity primary key,
  caso_id   bigint not null references public.reportes(id) on delete cascade,
  autor     text not null,
  texto     text not null check (length(texto) between 1 and 1000),
  creado_en timestamptz not null default now()
);

create table public.mensajes_caso (
  id         bigint generated by default as identity primary key,
  caso_id    bigint not null references public.reportes(id) on delete cascade,
  autor_tipo text not null check (autor_tipo in ('staff', 'usuario')),
  autor      text,
  texto      text not null check (length(texto) between 1 and 2000),
  creado_en  timestamptz not null default now()
);

create table public.actividad_caso (
  id        bigint generated by default as identity primary key,
  caso_id   bigint not null references public.reportes(id) on delete cascade,
  tipo      text not null,                  -- creado | estado | responsable | eliminado | restaurado
  anterior  text,
  nuevo     text,
  autor     text,
  creado_en timestamptz not null default now()
);

create index reportes_cliente_id_idx      on public.reportes (cliente_id);
create index notas_caso_caso_idx          on public.notas_caso (caso_id);
create index mensajes_caso_caso_idx       on public.mensajes_caso (caso_id);
create index actividad_caso_caso_idx      on public.actividad_caso (caso_id);
create index sesiones_cliente_cliente_idx on public.sesiones_cliente (cliente_id);

-- 2) ¿Quién es del equipo? (security definer: evita recursión en RLS) ----
create function public.staff_usuario()
returns text language sql stable security definer set search_path = public as $$
  select usuario from public.staff where email = lower(auth.jwt() ->> 'email') limit 1;
$$;

create function public.es_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select public.staff_usuario() is not null;
$$;

revoke all on function public.staff_usuario(), public.es_staff() from public;
grant execute on function public.staff_usuario(), public.es_staff() to authenticated;

