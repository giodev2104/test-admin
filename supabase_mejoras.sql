-- 11) Avisos instantáneos al portal (Realtime Broadcast, canal secreto por cliente)
-- ---------------------------------------------------------------------
create or replace function public.avisar_portal()
returns trigger language plpgsql security definer set search_path = public as $$
declare cid uuid; k uuid;
begin
  if tg_table_name = 'mensajes_caso' then
    select cliente_id into cid from reportes where id = new.caso_id;
  else
    cid := new.cliente_id;
  end if;
  if cid is null then
    return null;
  end if;
  select canal into k from clientes where id = cid;
  begin
    perform realtime.send(jsonb_build_object('t', now()), 'cambio', 'portal-' || k::text, false);
  exception when others then
    null;
  end;
  return null;
end
$$;

create or replace trigger avisar_portal after insert on public.mensajes_caso for each row execute function public.avisar_portal();
create or replace trigger avisar_portal after insert or update on public.reportes for each row execute function public.avisar_portal();
create or replace trigger avisar_portal after insert or update on public.webs_cliente for each row execute function public.avisar_portal();

-- ---------------------------------------------------------------------
-- Lo que recibe el portal (versión completa)
-- ---------------------------------------------------------------------
create or replace function public.cliente_datos(p_token text)
returns json language plpgsql stable security definer set search_path = public, extensions as $$
declare cid uuid := _cliente_de_token(p_token); c clientes;
begin
  if cid is null then raise exception 'SESION_CADUCADA'; end if;
  select * into c from clientes where id = cid;
  return json_build_object(
    'cliente', json_build_object('id', c.id, 'email', c.email, 'nombre', c.nombre, 'dominio', c.dominio,
                                 'telefono', c.telefono, 'canal', c.canal),
    'web', (select to_json(w) from webs_cliente w where w.cliente_id = cid),
    'historial', coalesce((select json_agg(json_build_object('mes', h.mes, 'datos', h.datos) order by h.mes desc)
                           from (select * from webs_cliente_historial where cliente_id = cid order by mes desc limit 12) h), '[]'::json),
    'casos', coalesce((select json_agg(x order by x.created_at desc) from (
        select id, tipo_reporte, titulo, estado, plan, plan_solicitado, dominio, urgencia, created_at
        from reportes where cliente_id = cid and eliminado_en is null) x), '[]'::json),
    'mensajes', coalesce((select json_agg(x order by x.creado_en) from (
        select m.id, m.caso_id, m.autor_tipo, m.autor, m.texto, m.creado_en,
               m.adjunto_ruta, m.adjunto_nombre, m.adjunto_tipo, m.adjunto_tamano
        from mensajes_caso m join reportes r on r.id = m.caso_id
        where r.cliente_id = cid and r.eliminado_en is null) x), '[]'::json));
end
$$;

