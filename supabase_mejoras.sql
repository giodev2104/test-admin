create table if not exists public.recuperaciones (
  token_hash text primary key,
  cliente_id uuid not null references public.clientes(id) on delete cascade,
  creado_en  timestamptz not null default now(),
  expira_en  timestamptz not null default now() + interval '1 hour',
  usado_en   timestamptz
);
alter table public.recuperaciones enable row level security;
revoke all on public.recuperaciones from anon, authenticated;

create or replace function public.servidor_crear_recuperacion(p_email text, p_ip text)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare c clientes; t text;
begin
  if _excedido('recuperar-ip:' || coalesce(p_ip, ''), 5, interval '1 hour') then
    return json_build_object('error', 'limite');
  end if;
  perform _anotar('recuperar-ip:' || coalesce(p_ip, ''));
  select * into c from clientes where email = lower(trim(coalesce(p_email, '')));
  if c.id is null then
    return null;
  end if;
  if exists (select 1 from recuperaciones where cliente_id = c.id and creado_en > now() - interval '5 minutes') then
    return json_build_object('error', 'reciente');
  end if;
  delete from recuperaciones where expira_en < now() - interval '1 day';
  t := encode(gen_random_bytes(32), 'hex');
  insert into recuperaciones (token_hash, cliente_id) values (encode(digest(t, 'sha256'), 'hex'), c.id);
  return json_build_object('token', t, 'nombre', c.nombre, 'email', c.email);
end
$$;

create or replace function public.cliente_restablecer_clave(p_token text, p_clave text)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare r recuperaciones;
begin
  if length(coalesce(p_clave, '')) < 8 then raise exception 'La contraseña debe tener al menos 8 caracteres.'; end if;
  select * into r from recuperaciones
    where token_hash = encode(digest(coalesce(p_token, ''), 'sha256'), 'hex') and usado_en is null and expira_en > now();
  if r.token_hash is null then
    raise exception 'El enlace ha caducado o ya se usó. Pide uno nuevo desde «¿Has olvidado tu contraseña?».';
  end if;
  update recuperaciones set usado_en = now() where token_hash = r.token_hash;
  update clientes set clave_hash = crypt(p_clave, gen_salt('bf')) where id = r.cliente_id;
  delete from sesiones_cliente where cliente_id = r.cliente_id;
  return _cliente_sesion(r.cliente_id);
end
$$;

revoke all on function public.servidor_crear_recuperacion(text, text), public.cliente_restablecer_clave(text, text) from public, anon, authenticated;
grant execute on function public.cliente_restablecer_clave(text, text) to anon, authenticated;

