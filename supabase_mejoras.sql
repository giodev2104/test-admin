create or replace function public.webs_cliente_sello()
returns trigger language plpgsql security definer set search_path = public as $$
declare quien text := public.staff_usuario();
begin
  if quien is not null then
    new.actualizado_en := now();
    new.actualizado_por := quien;
  elsif tg_op = 'INSERT' then
    new.actualizado_en := now();
    new.actualizado_por := coalesce(new.actualizado_por, 'sistema');
  else
    new.actualizado_en := old.actualizado_en;
    new.actualizado_por := old.actualizado_por;
  end if;
  return new;
end
$$;

create or replace function public.webs_cliente_registrar_cambios()
returns trigger language plpgsql security definer set search_path = public as $$
declare quien text := public.staff_usuario(); d jsonb;
begin
  if quien is null then
    return null;
  end if;
  select jsonb_object_agg(n.key, jsonb_build_array(o.value, n.value)) into d
  from jsonb_each(to_jsonb(new)) n
  left join jsonb_each(case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end) o using (key)
  where n.key not in ('cliente_id', 'actualizado_en', 'actualizado_por', 'pagespeed_en')
    and n.value is distinct from o.value
    and not (o.value is null and n.value in ('null'::jsonb, '[]'::jsonb));
  if d is not null then
    insert into webs_cliente_cambios (cliente_id, autor, cambios) values (new.cliente_id, quien, d);
  end if;
  return null;
end
$$;

create or replace trigger webs_cliente_cambios after insert or update on public.webs_cliente
  for each row execute function public.webs_cliente_registrar_cambios();

