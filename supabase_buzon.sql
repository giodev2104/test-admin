-- =====================================================================
--  Velority · Buzón de correo en el panel (contact-velority@velority.es)
-- =====================================================================
-- Los correos que llegan a la dirección de contacto se guardan aquí (los mete la función «buzon», que recibe
-- el aviso de Brevo) y el equipo los lee y responde desde el panel. Solo se guardan los correos recibidos y las
-- respuestas del equipo: los automáticos de la web (cambiar contraseña, avisos…) no pasan por aquí.
-- Ejecútalo en Supabase > SQL Editor. Se puede ejecutar varias veces.

create table if not exists public.correos (
  id             bigint generated by default as identity primary key,
  direccion      text not null check (direccion in ('entrada', 'salida')),
  contacto       text not null check (length(contacto) between 3 and 320),   -- el correo de la otra persona (en minúsculas)
  contacto_nombre text,
  asunto         text not null default '' check (length(asunto) <= 500),
  texto          text not null default '' check (length(texto) <= 60000),
  message_id     text,
  en_respuesta_a text,
  adjuntos       jsonb not null default '[]'::jsonb,
  enviado_por    text,                                                       -- usuario del equipo que respondió
  leido_en       timestamptz,
  creado_en      timestamptz not null default now()
);
create unique index if not exists correos_message_id_idx on public.correos (message_id) where message_id is not null;
create index if not exists correos_contacto_idx on public.correos (contacto, creado_en desc);

alter table public.correos enable row level security;
revoke all on public.correos from anon, authenticated;
grant select, update, delete on public.correos to authenticated;   -- insertar solo lo hace la función (service_role)
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'correos' and policyname = 'staff_lee_correos') then
    create policy "staff_lee_correos" on public.correos for select to authenticated using (public.es_staff());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'correos' and policyname = 'staff_marca_correos') then
    create policy "staff_marca_correos" on public.correos for update to authenticated using (public.es_staff()) with check (public.es_staff());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'correos' and policyname = 'staff_borra_correos') then
    create policy "staff_borra_correos" on public.correos for delete to authenticated using (public.es_staff());
  end if;
  -- Tiempo real: el panel se entera al momento de los correos nuevos
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'correos') then
    alter publication supabase_realtime add table public.correos;
  end if;
end
$$;
