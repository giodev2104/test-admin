-- =====================================================================
--  Webcare · Entregas de archivos (web en .html, .zip, PDF, diseños…)
-- =====================================================================
-- Ejecútalo en Supabase > SQL Editor DESPUÉS de supabase_servicios.sql.
-- No borra datos y se puede ejecutar varias veces.
--
-- El equipo sube los archivos de cada pedido desde el panel (ficha completa del cliente >
-- Servicios contratados) y marca el pedido como pagado. El cliente ve la entrega en su portal
-- y solo puede descargarla cuando el pedido está pagado (lo comprueba la función «adjuntos»).
-- Los archivos van al bucket privado «entregas» (hasta 50 MB por archivo, cualquier tipo).
-- =====================================================================

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('entregas', 'entregas', false, 52428800, null)
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = null;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'staff_lee_entregas') then
    create policy "staff_lee_entregas" on storage.objects for select to authenticated
      using (bucket_id = 'entregas' and public.es_staff());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'staff_sube_entregas') then
    create policy "staff_sube_entregas" on storage.objects for insert to authenticated
      with check (bucket_id = 'entregas' and public.es_staff());
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'staff_quita_entregas') then
    create policy "staff_quita_entregas" on storage.objects for delete to authenticated
      using (bucket_id = 'entregas' and public.es_staff());
  end if;
end
$$;

-- Pago de cada pedido (lo marca el equipo al ver el cobro en Stripe)
alter table public.servicios_cliente add column if not exists pagado_en  timestamptz;
alter table public.servicios_cliente add column if not exists pagado_por text;

create table if not exists public.entregas (
  id            bigint generated by default as identity primary key,
  cliente_id    uuid not null references public.clientes(id) on delete cascade,
  servicio_id   bigint references public.servicios_cliente(id) on delete set null,
  nombre        text not null check (length(nombre) between 1 and 200),
  ruta          text not null unique,
  tipo          text,
  tamano        bigint,
  nota          text check (nota is null or length(nota) <= 500),
  subido_por    text,
  creado_en     timestamptz not null default now(),
  descargado_en timestamptz,
  descargas     int not null default 0
);
create index if not exists entregas_cliente_idx on public.entregas (cliente_id);
alter table public.entregas enable row level security;
revoke all on public.entregas from anon, authenticated;
grant select, insert, update, delete on public.entregas to authenticated;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'entregas' and policyname = 'staff_entregas') then
    create policy "staff_entregas" on public.entregas for all to authenticated
      using (public.es_staff()) with check (public.es_staff());
  end if;
end
$$;

-- El portal se entera al momento cuando hay una entrega nueva
create or replace trigger avisar_portal after insert or update on public.entregas
  for each row execute function public.avisar_portal();

-- El portal recibe también las entregas y si cada pedido está pagado (versión 5 de cliente_datos)
create or replace function public.cliente_datos(p_token text)
returns json language plpgsql stable security definer set search_path = public, extensions as $$
declare cid uuid := _cliente_de_token_lectura(p_token); c clientes; lectura boolean;
begin
  if cid is null then raise exception 'SESION_CADUCADA'; end if;
  select * into c from clientes where id = cid;
  select solo_lectura into lectura from sesiones_cliente where token_hash = encode(digest(coalesce(p_token, ''), 'sha256'), 'hex');
  return json_build_object(
    'cliente', json_build_object('id', c.id, 'email', c.email, 'nombre', c.nombre, 'dominio', c.dominio,
                                 'telefono', c.telefono, 'canal', c.canal),
    'solo_lectura', coalesce(lectura, false),
    'web', (select to_json(w) from webs_cliente w where w.cliente_id = cid),
    'historial', coalesce((select json_agg(json_build_object('mes', h.mes, 'datos', h.datos) order by h.mes desc)
                           from (select * from webs_cliente_historial where cliente_id = cid order by mes desc limit 12) h), '[]'::json),
    'casos', coalesce((select json_agg(x order by x.created_at desc) from (
        select id, tipo_reporte, titulo, estado, plan, plan_solicitado, dominio, urgencia, created_at, resuelto_en, origen
        from reportes where cliente_id = cid and eliminado_en is null) x), '[]'::json),
    'mensajes', coalesce((select json_agg(x order by x.creado_en) from (
        select m.id, m.caso_id, m.autor_tipo, m.autor, m.texto, m.creado_en,
               m.adjunto_ruta, m.adjunto_nombre, m.adjunto_tipo, m.adjunto_tamano, m.leido_cliente_en, m.leido_staff_en
        from mensajes_caso m join reportes r on r.id = m.caso_id
        where r.cliente_id = cid and r.eliminado_en is null) x), '[]'::json),
    'valoraciones', coalesce((select json_agg(json_build_object('caso_id', v.caso_id, 'estrellas', v.estrellas))
                              from valoraciones v where v.cliente_id = cid), '[]'::json),
    'renovaciones', coalesce((select json_agg(json_build_object('concepto', x.concepto, 'fecha', x.fecha, 'tipo', x.tipo) order by x.fecha)
                              from renovaciones x where x.cliente_id = cid and x.hecho_en is null
                                and x.fecha >= current_date - 30 and x.fecha <= current_date + 365), '[]'::json),
    'servicios', coalesce((select json_agg(json_build_object('id', s.id, 'tipo', s.tipo, 'nombre', s.nombre, 'precio', s.precio,
                                  'estado', s.estado, 'caso_id', s.caso_id, 'caso_baja_id', s.caso_baja_id, 'nota', s.nota,
                                  'creado_en', s.creado_en, 'activado_en', s.activado_en, 'baja_en', s.baja_en, 'pagado_en', s.pagado_en) order by s.creado_en desc)
                           from servicios_cliente s where s.cliente_id = cid and s.estado <> 'rechazado'), '[]'::json),
    'entregas', coalesce((select json_agg(json_build_object('id', e.id, 'servicio_id', e.servicio_id, 'nombre', e.nombre, 'tipo', e.tipo,
                                  'tamano', e.tamano, 'nota', e.nota, 'creado_en', e.creado_en, 'descargado_en', e.descargado_en) order by e.creado_en desc)
                          from entregas e where e.cliente_id = cid), '[]'::json));
end
$$;

select 'Entregas listas' as resultado;
